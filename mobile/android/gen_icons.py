"""Writes app/src/main/java/org/rcad/mobile/IconPaths.kt from the editor's icon set (src/icon_paths.rs),
so the phone app draws the same stroked icons. Run it again when that file changes."""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "..", "src", "icon_paths.rs")).read()
icons = re.findall(r'\("([A-Za-z0-9_-]+)",\s*"([^"]*)"\)', src)
out = ["// Generated by mobile/android/gen_icons.py from src/icon_paths.rs. Do not edit.",
       "package org.rcad.mobile", "",
       "/** The editor's icons: SVG path data on a 24 x 24 grid, drawn stroked (see [Icon]). */",
       "object IconPaths {",
       "    val all: Map<String, String> = mapOf("]
out += [f'        "{n}" to "{d}",' for n, d in icons]
out += ["    )", "}", ""]
open(os.path.join(here, "app/src/main/java/org/rcad/mobile/IconPaths.kt"), "w").write("\n".join(out))
print(len(icons), "icons")
